"""gRPC front end: the same GatewayCore as the REST API, so routing, caching, budget and metrics behave identically."""
import asyncio
import logging

import grpc

from app import gateway_pb2, gateway_pb2_grpc          # generated by scripts/gen_proto.py
from app.core import GatewayCore, GatewayError
from app.models import QueryRequest

logger = logging.getLogger("gateway.grpc")

_CODES = {429: grpc.StatusCode.RESOURCE_EXHAUSTED, 502: grpc.StatusCode.UNAVAILABLE}
_background: set[asyncio.Task] = set()


def _schedule(fn, *args) -> None:
    """Run a cache write after the reply is sent (keeping a reference so the task isn't garbage collected)."""
    task = asyncio.ensure_future(fn(*args))
    _background.add(task)
    task.add_done_callback(_background.discard)


class GatewayServicer(gateway_pb2_grpc.GatewayServicer):
    def __init__(self, core: GatewayCore):
        self.core = core

    async def Query(self, request, context):
        if not request.prompt.strip():
            await context.abort(grpc.StatusCode.INVALID_ARGUMENT, "prompt must not be empty")
        req = QueryRequest(prompt=request.prompt,
                           temperature=request.temperature or 0.7,
                           max_tokens=request.max_tokens or 1000,
                           force_cloud=request.force_cloud)
        try:
            r = await self.core.handle(req, _schedule)
        except GatewayError as e:
            await context.abort(_CODES.get(e.status_code, grpc.StatusCode.INTERNAL), e.detail)
        return gateway_pb2.QueryResponse(response=r.response, source=r.source, latency_ms=r.latency_ms,
                                         tokens_used=r.tokens_used, cost_usd=r.cost_usd)

    async def Health(self, request, context):
        h = await self.core.health()
        return gateway_pb2.HealthResponse(status=h["status"], local_connected=h["local_ollama_connected"],
                                          cloud_configured=h["cloud_gemini_configured"])


async def start_grpc(core: GatewayCore, port: int) -> grpc.aio.Server:
    """Start serving on `port` (0 picks a free one; read it back from server.bound_port)."""
    server = grpc.aio.server()
    gateway_pb2_grpc.add_GatewayServicer_to_server(GatewayServicer(core), server)
    server.bound_port = server.add_insecure_port(f"[::]:{port}")
    await server.start()
    return server
